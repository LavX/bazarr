#!/usr/bin/env python3
"""Write bazarr/subtitles/tools/ocr/tessdata_checksums.py for one tessdata_fast tag.

Lists the tag's top-level .traineddata files through the GitHub API, downloads
each one, checks it against the size and git blob hash the tag records, and
writes the size and SHA-256 Bazarr+ verifies downloads against. The git check
ties every recorded checksum to the tagged tree rather than to whatever the
download served that day.

    python3 scripts/ocr/generate_tessdata_checksums.py            # every pack, about 355 MB
    python3 scripts/ocr/generate_tessdata_checksums.py --only eng,hun --output /tmp/partial.py

Standard library only, so it runs before the application's requirements are
installed.
"""

import argparse
import hashlib
import json
import os
import sys
import urllib.request

REPOSITORY = "tesseract-ocr/tessdata_fast"
TAG = "4.1.0"
DEFAULT_OUTPUT = os.path.join(os.path.dirname(__file__), "..", "..", "bazarr", "subtitles", "tools", "ocr",
                              "tessdata_checksums.py")


def _get(url):
    request = urllib.request.Request(url, headers={"User-Agent": "bazarr-tessdata-checksums"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def tagged_packs(repository, tag):
    tree = json.loads(_get(f"https://api.github.com/repos/{repository}/git/trees/{tag}"))
    if tree.get("truncated"):
        raise SystemExit("The GitHub tree listing was truncated; cannot trust it")
    return {entry["path"][:-len(".traineddata")]: (entry["size"], entry["sha"])
            for entry in tree["tree"]
            if entry["type"] == "blob" and entry["path"].endswith(".traineddata") and "/" not in entry["path"]}


def checksum(repository, tag, name, size, blob_sha):
    data = _get(f"https://raw.githubusercontent.com/{repository}/{tag}/{name}.traineddata")
    if len(data) != size:
        raise SystemExit(f"{name}: downloaded {len(data)} bytes, the tag records {size}")
    if hashlib.sha1(b"blob %d\0" % size + data).hexdigest() != blob_sha:
        raise SystemExit(f"{name}: the download does not match the tagged git blob {blob_sha}")
    return hashlib.sha256(data).hexdigest()


def render(repository, tag, rows):
    lines = [
        "# coding=utf-8",
        f"# Generated by scripts/ocr/generate_tessdata_checksums.py from {repository} at {tag}.",
        "# Do not edit by hand; run the script again to change the tag.",
        "",
        f'TESSDATA_REPOSITORY = "{repository}"',
        f'TESSDATA_TAG = "{tag}"',
        "",
        "# pack name -> (size in bytes, SHA-256)",
        "TESSDATA_CHECKSUMS = {",
    ]
    lines += [f'    "{name}": ({size}, "{sha256}"),' for name, size, sha256 in sorted(rows)]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", default=TAG)
    parser.add_argument("--only", help="comma-separated pack names, for a partial table")
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    options = parser.parse_args(argv)

    packs = tagged_packs(REPOSITORY, options.tag)
    wanted = sorted(packs) if not options.only else options.only.split(",")
    rows = []
    for name in wanted:
        size, blob_sha = packs[name]
        rows.append((name, size, checksum(REPOSITORY, options.tag, name, size, blob_sha)))
        print(f"{name}: {size} bytes", file=sys.stderr)
    with open(options.output, "w", encoding="utf-8") as handle:
        handle.write(render(REPOSITORY, options.tag, rows))
    print(f"Wrote {len(rows)} packs to {options.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
