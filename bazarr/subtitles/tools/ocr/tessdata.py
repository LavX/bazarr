# coding=utf-8
"""Tesseract language packs, fetched on first use and verified by checksum.

Packs come from tessdata_fast at one pinned tag. Every file in that tag has a
size and SHA-256 in tessdata_checksums.py, generated by
scripts/ocr/generate_tessdata_checksums.py, so a download that does not match
is refused and a file placed by hand is accepted only when it does match.
"""

import hashlib
import logging
import os
import uuid

import requests

from .errors import LanguagePackError
from .tessdata_checksums import TESSDATA_CHECKSUMS, TESSDATA_REPOSITORY, TESSDATA_TAG

logger = logging.getLogger(__name__)

DOWNLOAD_TIMEOUT = (10, 60)
_CHUNK = 1 << 16

# Bazarr's own three-letter codes (languages/custom_lang.py) and the ISO codes
# whose Tesseract pack has another name. Norwegian Bokmal and Nynorsk share
# tessdata's one Norwegian pack.
_OFFICIAL_ALPHA3 = {"pob": "por", "spl": "spa", "zht": "zho"}
_PACK_NAMES = {"zho": "chi_sim", "zht": "chi_tra", "nob": "nor", "nno": "nor"}


def tessdata_dir():
    """``ocr.tessdata_dir``, or ``tessdata`` in the config folder when it is empty."""
    from app.config import settings
    from app.get_args import args

    configured = (settings.ocr.tessdata_dir or "").strip()
    return configured or os.path.join(args.config_dir, "tessdata")


def official_alpha3(code):
    """The ISO 639-3 code for a track or profile language code, or None."""
    from babelfish import Error as BabelfishError, Language

    code = (code or "").strip().lower()
    if code in _OFFICIAL_ALPHA3:
        return _OFFICIAL_ALPHA3[code]
    for build in (Language, Language.fromalpha3b):
        try:
            return build(code).alpha3
        except (ValueError, BabelfishError):
            continue
    return None


def pack_name(code):
    """The tessdata_fast pack for a language code. Raises before any download."""
    canonical = official_alpha3(code)
    name = _PACK_NAMES.get((code or "").strip().lower()) or _PACK_NAMES.get(canonical) or canonical
    if not name or name not in TESSDATA_CHECKSUMS:
        raise LanguagePackError(f"No OCR language pack for {code or 'an unknown language'}")
    return name


def pack_url(name):
    return f"https://raw.githubusercontent.com/{TESSDATA_REPOSITORY}/{TESSDATA_TAG}/{name}.traineddata"


def _matches(path, expected):
    size, sha256 = expected
    try:
        if os.path.getsize(path) != size:
            return False
        digest = hashlib.sha256()
        with open(path, "rb") as handle:
            for block in iter(lambda: handle.read(_CHUNK), b""):
                digest.update(block)
    except OSError:
        return False
    return digest.hexdigest() == sha256


def ensure_pack(code, directory, progress=None):
    """Make ``<directory>/<pack>.traineddata`` present and verified; return the pack name."""
    name = pack_name(code)
    expected = TESSDATA_CHECKSUMS[name]
    target = os.path.join(directory, f"{name}.traineddata")
    if _matches(target, expected):
        return name

    url = pack_url(name)
    partial = f"{target}.{uuid.uuid4().hex}.part"
    size, sha256 = expected
    try:
        os.makedirs(directory, exist_ok=True)
        digest = hashlib.sha256()
        written = 0
        with requests.get(url, stream=True, timeout=DOWNLOAD_TIMEOUT) as response:
            response.raise_for_status()
            with open(partial, "wb") as handle:
                for block in response.iter_content(_CHUNK):
                    written += len(block)
                    if written > size:
                        break
                    digest.update(block)
                    handle.write(block)
                    if progress:
                        progress("pack", written, size)
        if written != size or digest.hexdigest() != sha256:
            raise LanguagePackError(
                f"The OCR language pack downloaded from {url} does not match its checksum and was "
                f"refused. Download it by hand and place it in {directory}")
        os.replace(partial, target)
    except LanguagePackError:
        raise
    except (requests.RequestException, OSError) as error:
        raise LanguagePackError(
            f"Could not download the OCR language pack {name}.traineddata from {url} ({error}). "
            f"Download that file and place it in {directory}") from error
    finally:
        if os.path.exists(partial):
            try:
                os.remove(partial)
            except OSError:
                logger.debug("Could not remove the partial download %s", partial)
    logger.info("Downloaded the OCR language pack %s into %s", name, directory)
    return name
