# coding=utf-8
"""Build bitmap subtitle fixtures for the OCR tests without an external tool.

ffmpeg can decode PGS but has no PGS encoder, and it cannot turn a text
subtitle into a bitmap one. So the tests carry a minimal Blu-ray PGS writer:
enough of the format (presentation, window, palette and object segments, with
the run-length coding the object data uses) for ffmpeg's decoder to render
each cue exactly where and when it was placed. A VobSub fixture is then made
from a PGS one with ffmpeg's own dvdsub encoder, which accepts bitmap input.

The committed .sup fixtures under tests/bazarr/fixtures/ocr/ were generated by
running this module as a script with a DejaVu Sans font; see main() below.
Tests that only need shapes (blank cues, tiny crops) build their streams here
at run time and need no font.
"""

import os
import struct

PGS_TICKS_PER_MS = 90

_PCS, _WDS, _PDS, _ODS, _END = 0x16, 0x17, 0x14, 0x15, 0x80
_ODS_CHUNK = 0xFFFF - 11  # segment payload limit minus the ODS header fields

# Palette index -> (Y, Cr, Cb, alpha). Index 0 is left undefined, which the
# decoder treats as fully transparent.
# FAINT is all but invisible: a cue drawn with it is on screen and empty.
WHITE, BLACK, FAINT = 1, 2, 3
_PALETTE = {WHITE: (235, 128, 128, 255), BLACK: (16, 128, 128, 255), FAINT: (16, 128, 128, 1)}


def _segment(kind, payload, pts_ms):
    pts = int(round(pts_ms * PGS_TICKS_PER_MS))
    return b"PG" + struct.pack(">IIBH", pts, 0, kind, len(payload)) + payload


def encode_rle(rows):
    """PGS run-length coding of a 2D list of palette indices."""
    out = bytearray()
    for row in rows:
        i, n = 0, len(row)
        while i < n:
            colour = row[i]
            j = i
            while j < n and row[j] == colour and j - i < 0x3FFF:
                j += 1
            length = j - i
            if colour != 0 and length < 3:
                out += bytes([colour]) * length
            elif colour == 0:
                out += bytes([0, length]) if length < 64 else bytes([0, 0x40 | (length >> 8), length & 0xFF])
            else:
                out += (bytes([0, 0x80 | length, colour]) if length < 64
                        else bytes([0, 0xC0 | (length >> 8), length & 0xFF, colour]))
            i = j
        out += b"\x00\x00"
    return bytes(out)


def _display_set(canvas, number, pts_ms, obj=None):
    width, height = canvas
    if obj is None:
        # A clear: a composition with no objects over the same window.
        pcs = struct.pack(">HHBHBBBB", width, height, 0x10, number, 0x00, 0, 0, 0)
        wds = struct.pack(">BBHHHH", 1, 0, 0, 0, width, height)
        return _segment(_PCS, pcs, pts_ms) + _segment(_WDS, wds, pts_ms) + _segment(_END, b"", pts_ms)
    x, y, rows = obj
    obj_w, obj_h = len(rows[0]), len(rows)
    pcs = struct.pack(">HHBHBBBB", width, height, 0x10, number, 0x80, 0, 0, 1)
    pcs += struct.pack(">HBBHH", 0, 0, 0, x, y)
    wds = struct.pack(">BBHHHH", 1, 0, x, y, obj_w, obj_h)
    pds = struct.pack(">BB", 0, 0) + b"".join(struct.pack(">BBBBB", i, *v) for i, v in _PALETTE.items())
    data = struct.pack(">HH", obj_w, obj_h) + encode_rle(rows)
    chunks = [data[k:k + _ODS_CHUNK] for k in range(0, len(data), _ODS_CHUNK)]
    ods = b""
    for index, chunk in enumerate(chunks):
        flag = (0x80 if index == 0 else 0) | (0x40 if index == len(chunks) - 1 else 0)
        header = struct.pack(">HBB", 0, 0, flag)
        if index == 0:
            header += struct.pack(">I", len(data))[1:]
        ods += _segment(_ODS, header + chunk, pts_ms)
    return (_segment(_PCS, pcs, pts_ms) + _segment(_WDS, wds, pts_ms) + _segment(_PDS, pds, pts_ms)
            + ods + _segment(_END, b"", pts_ms))


def build_sup(canvas, cues):
    """A PGS stream. ``cues`` is a list of (start_ms, end_ms, x, y, rows)."""
    out = bytearray()
    number = 0
    for start, end, x, y, rows in cues:
        out += _display_set(canvas, number, start, (x, y, rows))
        out += _display_set(canvas, number + 1, end)
        number += 2
    return bytes(out)


def box_rows(width, height, colour=WHITE):
    """A solid rectangle: a cue with content but no text."""
    return [[colour] * width for _ in range(height)]


def text_rows(text, font_path, size, stroke=3):
    """Render ``text`` white with a black outline and quantise it to the palette."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(font_path, size)
    lines = text.split("\n")
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    boxes = [probe.textbbox((0, 0), line, font=font, stroke_width=stroke) for line in lines]
    line_h = max(b[3] - b[1] for b in boxes) + 8
    width = max(b[2] - b[0] for b in boxes) + 2 * stroke + 8
    height = line_h * len(lines) + 2 * stroke
    fill = Image.new("L", (width, height), 0)
    outline = Image.new("L", (width, height), 0)
    for index, (line, box) in enumerate(zip(lines, boxes)):
        at = (stroke + 4 - box[0], stroke + index * line_h - box[1])
        ImageDraw.Draw(outline).text(at, line, font=font, fill=255, stroke_width=stroke, stroke_fill=255)
        ImageDraw.Draw(fill).text(at, line, font=font, fill=255)
    rows = []
    for y in range(height):
        row = []
        for x in range(width):
            if fill.getpixel((x, y)) >= 128:
                row.append(WHITE)
            elif outline.getpixel((x, y)) >= 128:
                row.append(BLACK)
            else:
                row.append(0)
        rows.append(row)
    return rows


FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "ocr")

# (start_ms, end_ms, text). The English "l don't" is the classic OCR misread
# of "I don't" that the OCR Fixes mod repairs.
ENGLISH_CUES = [
    (1000, 3500, "Hello there, how are you?"),
    (5000, 7250, "We need to leave\nbefore the storm."),
    (9000, 11000, "l don't know."),
]
# Every Hungarian accented letter, lower and upper case.
HUNGARIAN_CUES = [
    (1000, 3500, "árvíztűrő tükörfúrógép"),
    (5000, 7250, "ÁRVÍZTŰRŐ TÜKÖRFÚRÓGÉP"),
    (9000, 11000, "Öt szép szűz lány őrült írót nyúz."),
]
# name -> (canvas, cues, font size, outline)
TEXT_FIXTURES = {
    "eng_hd.sup": ((1920, 1080), ENGLISH_CUES, 48, 3),
    "hun_hd.sup": ((1920, 1080), HUNGARIAN_CUES, 48, 3),
    "hun_sd.sup": ((720, 576), HUNGARIAN_CUES, 24, 2),
}


def bottom_centre(canvas, rows, margin):
    return (canvas[0] - len(rows[0])) // 2, canvas[1] - margin - len(rows)


def text_sup(canvas, cues, font_path, size, stroke):
    placed = []
    for start, end, text in cues:
        rows = text_rows(text, font_path, size, stroke)
        x, y = bottom_centre(canvas, rows, canvas[1] // 12)
        placed.append((start, end, x, y, rows))
    return build_sup(canvas, placed)


def mux_mkv(ffmpeg, output, subtitles, seconds=13):
    """An MKV with a small black video and the given subtitle streams.

    ``subtitles`` is a list of (source path, codec, language); codec is
    ``copy`` for PGS or ``dvdsub`` to re-encode a PGS source as VobSub.
    """
    import subprocess

    # -copyts keeps each cue at its own time; without it ffmpeg would move every
    # input to start at zero, and a .sup starts at its first cue.
    command = [ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-copyts",
               "-f", "lavfi", "-i", f"color=c=black:s=64x64:r=5:d={seconds}"]
    for source, _, _ in subtitles:
        # PGS closes a cue with a separate empty display set; a re-encode to
        # dvdsub only carries the end time when the decoder folds it in.
        command += ["-fix_sub_duration", "-i", source]
    command += ["-map", "0:v"]
    for index in range(len(subtitles)):
        command += ["-map", f"{index + 1}:s"]
    command += ["-c:v", "mpeg4"]
    for index, (_, codec, language) in enumerate(subtitles):
        command += [f"-c:s:{index}", codec, f"-metadata:s:s:{index}", f"language={language}"]
    command.append(output)
    subprocess.run(command, check=True, capture_output=True)
    return output


def main(argv=None):
    import argparse

    parser = argparse.ArgumentParser(description="Regenerate the committed OCR .sup fixtures.")
    parser.add_argument("--font", required=True, help="path to DejaVuSans.ttf")
    options = parser.parse_args(argv)
    os.makedirs(FIXTURES, exist_ok=True)
    for name, (canvas, cues, size, stroke) in TEXT_FIXTURES.items():
        data = text_sup(canvas, cues, options.font, size, stroke)
        with open(os.path.join(FIXTURES, name), "wb") as handle:
            handle.write(data)
        print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
